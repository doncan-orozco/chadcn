#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerates the component library's icons/catalog.rb (see layout.rb) from the REAL lucide-react exports of the React catalog (layout.rb CATALOG_DIR).
# Names = union of: manifest `icons`, every `<icon:name>` in scenarios, and the lucide imports of the oracle sources.
# Resolution is the one of <catalog>/src/parity/Harness.tsx (`<Pascal>Icon` first, then `<Pascal>`);
# PascalCase export names (manifests/sources) resolve directly.
#   ruby .claude/scripts/shadcn/icons_sync.rb           # rewrite catalog.rb
#   ruby .claude/scripts/shadcn/icons_sync.rb --check   # exit 1 when the catalog lacks a required name (writes nothing)
require_relative "layout"
require "json"
require "open3"
require "pathname"

ROOT = Pathname.new(__dir__).join("../../..").expand_path
CATALOG = ROOT.join(ShadcnLayout::RUBY_DIR, "icons/catalog.rb")
REACT = ROOT.join(ShadcnLayout::CATALOG_DIR)

def required_names
  names = Dir[ROOT.join(ShadcnLayout::ORACLE_DIR, "manifest/*.json")].flat_map { |f| JSON.parse(File.read(f))["icons"] || [] }
  names += Dir[ROOT.join(ShadcnLayout::SCENARIOS_DIR, "*.json")].flat_map { |f| File.read(f).scan(/<icon:([a-z0-9-]+)>/).flatten }
  Dir[REACT.join("src/components/ui/*.tsx")].each do |f|
    File.read(f).scan(/import\s*\{([^}]*)\}\s*from\s*"lucide-react"/m).flatten.each do |list|
      names += list.split(",").map { |n| n.strip.split(/\s+as\s+/).first }.reject { |n| n.nil? || n.empty? }
    end
  end
  names.uniq.sort
end

NODE = <<~JS
  import * as L from "lucide-react"
  import React from "react"
  import { renderToStaticMarkup } from "react-dom/server"
  const pascal = (s) => s.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("")
  const names = JSON.parse(process.argv[1])
  const out = {}
  for (const name of names) {
    const C = /^[A-Z]/.test(name) ? L[name] : (L[`${pascal(name)}Icon`] ?? L[pascal(name)])
    if (!C) { out[name] = null; continue }
    out[name] = renderToStaticMarkup(React.createElement(C))
  }
  console.log(JSON.stringify(out))
JS

def render_all(names)
  out, err, status = Open3.capture3("node", "--input-type=module", "-e", NODE, JSON.generate(names), chdir: REACT.to_s)
  abort "node failed: #{err}" unless status.success?
  JSON.parse(out)
end

def parse(name, html)
  m = html.match(/\A<svg [^>]*class="lucide ((?:lucide-[a-z0-9-]+ ?)+)" aria-hidden="true">(.*)<\/svg>\z/m) or abort "unexpected markup for #{name}: #{html}"
  classes = m[1].split
  [ classes.last.delete_prefix("lucide-"), m[2], classes.size > 1 ? "lucide #{m[1]}" : nil ]
end

def current_catalog
  return [ {}, {} ] unless CATALOG.exist?

  src = CATALOG.read
  [ src.scan(/^    "([a-z0-9-]+)" => /).flatten, src.scan(/^    "([A-Za-z0-9-]+)" => "([a-z0-9-]+)",?$/).to_h ]
end

names = required_names
rendered = render_all(names)
unknown = rendered.select { |_, html| html.nil? }.keys
abort "unknown lucide icons: #{unknown.join(', ')}" if unknown.any?

nodes = {}
classes = {}
aliases = {}
rendered.each do |name, html|
  key, inner, css = parse(name, html)
  nodes[key] = inner
  classes[key] = css if css
  aliases[name] = key unless name == key
end

if ARGV.include?("--check")
  have_nodes, have_aliases = current_catalog
  missing = nodes.keys - have_nodes
  missing_aliases = aliases.reject { |k, v| have_aliases[k] == v }.keys
  if missing.empty? && missing_aliases.empty?
    puts "icons catalog ok (#{nodes.size} icons)"
    exit 0
  end
  warn "icons catalog is stale (run icons_sync.rb): missing icons #{missing.inspect}, missing aliases #{missing_aliases.inspect}"
  exit 1
end

lucide_version = JSON.parse(REACT.join("node_modules/lucide-react/package.json").read)["version"]
lines = []
lines << "# Generated by .claude/scripts/shadcn/icons_sync.rb from lucide-react #{lucide_version}; do not edit by hand."
lines << "# Names = union of oracle manifest `icons`, `<icon:name>` in scenarios and lucide imports of the oracle sources."
lines << "module #{ShadcnLayout::NAMESPACE}::Icons::Catalog"
lines << "  VERSION = #{lucide_version.inspect}"
lines << ""
lines << "  # kebab-case lucide name (the `lucide-<name>` class) => inner SVG markup"
lines << "  NODES = {"
lines << nodes.sort.map { |k, v| "    #{k.inspect} => #{v.inspect}" }.join(",\n")
lines << "  }.freeze"
lines << ""
lines << "  # full class attribute for icons whose lucide-react markup carries several `lucide-*` classes"
lines << "  CLASSES = {"
lines << classes.sort.map { |k, v| "    #{k.inspect} => #{v.inspect}" }.join(",\n")
lines << "  }.freeze"
lines << ""
lines << "  # every accepted spelling (harness `<icon:name>` names, React export names) => NODES key"
lines << "  ALIASES = {"
lines << aliases.sort.map { |k, v| "    #{k.inspect} => #{v.inspect}" }.join(",\n")
lines << "  }.freeze"
lines << "end"
CATALOG.write("#{lines.join("\n")}\n")
puts "wrote #{CATALOG.relative_path_from(ROOT)}: #{nodes.size} icons, #{aliases.size} aliases"
