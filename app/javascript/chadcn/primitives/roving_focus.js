// Radix RovingFocusGroup (react-roving-focus/dist/index.mjs, v1.1.20) on server-rendered markup.
//   container: the group element. Items are its `[data-radix-collection-item]` descendants; a disabled item
//   (`data-disabled`) is not focusable (Radix `focusable={false}`).
// The server renders `tabindex="0"` on the group, `tabindex="-1"` on every item (or "0" on the initial tab stop) and
// `data-orientation`; this module only keeps them in sync afterwards.
//
// rovingFocus(container, {
//   orientation, loop = false, dir, currentTabStopId, preventScrollOnEntryFocus = false,
//   isActive = () => false,                 // Radix item `active` prop (e.g. the checked radio, the selected tab)
//   onCurrentTabStopIdChange, onEntryFocus  // onEntryFocus may call event.preventDefault() to take over entry focus
// }) => { release, currentTabStop, setCurrentTabStop }
//
// Known divergences: tab stop ids are the item's `data-tab-stop-id` or `id` (generated by ids.js when absent, like Radix useId), because
// there is no React item registry; items of a nested group inside the container are treated as this group's items (the DOM is the registry,
// see collection.js).
import { direction } from "chadcn/primitives/direction"
import { ensureId } from "chadcn/primitives/ids"
import { items as collectionItems, ITEM_SELECTOR } from "chadcn/primitives/collection"

const ENTRY_FOCUS = "rovingFocusGroup.onEntryFocus"
const MAP_KEY_TO_FOCUS_INTENT = {
  ArrowLeft: "prev", ArrowUp: "prev", ArrowRight: "next", ArrowDown: "next",
  PageUp: "first", Home: "first", PageDown: "last", End: "last",
}

const tabStopId = (el) => el.getAttribute("data-tab-stop-id") || ensureId(el)

function focusIntent(event, orientation, dir) {
  let key = event.key
  if (dir === "rtl") key = key === "ArrowLeft" ? "ArrowRight" : key === "ArrowRight" ? "ArrowLeft" : key
  if (orientation === "vertical" && ["ArrowLeft", "ArrowRight"].includes(key)) return undefined
  if (orientation === "horizontal" && ["ArrowUp", "ArrowDown"].includes(key)) return undefined
  return MAP_KEY_TO_FOCUS_INTENT[key]
}

function focusFirst(candidates, preventScroll = false) {
  const previous = document.activeElement
  for (const candidate of candidates) {
    if (candidate === previous) return
    candidate.focus({ preventScroll })
    if (document.activeElement !== previous) return
  }
}

const wrapArray = (array, start) => array.map((_, index) => array[(start + index) % array.length])

/**
 * Roving tabindex group (Radix RovingFocusGroup) over `[data-radix-collection-item]` descendants.
 * @param {HTMLElement} container
 * @param {object} [options]
 * @param {"horizontal" | "vertical"} [options.orientation] Both axes when omitted.
 * @param {boolean} [options.loop=false]
 * @param {"ltr" | "rtl"} [options.dir]
 * @param {string | null} [options.currentTabStopId]
 * @param {boolean} [options.preventScrollOnEntryFocus=false]
 * @param {(item: HTMLElement) => boolean} [options.isActive] Predicate called per item; the first enabled item it accepts takes entry focus first (checked radio, selected tab).
 * @param {(id: string | null) => void} [options.onCurrentTabStopIdChange]
 * @param {(event: CustomEvent) => void} [options.onEntryFocus] Cancelable; `preventDefault()` takes over entry focus.
 * @returns {{ currentTabStop: () => string | null, setCurrentTabStop: (id: string | null) => void, release: () => void }}
 *   `release()` disconnects the observer and removes every listener; tabindex values stay as last rendered.
 * @example
 * const group = rovingFocus(listEl, { orientation: "vertical", loop: true })
 */
export function rovingFocus(container, options = {}) {
  const { orientation, loop = false, preventScrollOnEntryFocus = false, isActive = () => false, onCurrentTabStopIdChange, onEntryFocus } = options
  const dirOf = () => direction(container, options.dir)
  const all = () => collectionItems(container, { includeDisabled: true })
  const focusable = () => collectionItems(container)
  const itemOf = (node) => (node instanceof Element ? node.closest(ITEM_SELECTOR) : null)

  let currentId = options.currentTabStopId ?? null
  let isTabbingBackOut = false
  let isClickFocus = false

  function render() {
    container.tabIndex = isTabbingBackOut || focusable().length === 0 ? -1 : 0
    for (const item of all()) {
      const tab = currentId !== null && tabStopId(item) === currentId ? 0 : -1
      if (item.tabIndex !== tab) item.tabIndex = tab
    }
  }

  function setCurrent(id) {
    if (id === currentId) return
    currentId = id
    onCurrentTabStopIdChange?.(id)
    render()
  }

  const onMouseDown = (event) => {
    isClickFocus = true
    const item = itemOf(event.target)
    if (!item) return
    if (!focusable().includes(item)) event.preventDefault()
    else setCurrent(tabStopId(item))
  }

  const onFocusIn = (event) => {
    const item = itemOf(event.target)
    if (item) setCurrent(tabStopId(item))
    const isKeyboardFocus = !isClickFocus
    if (event.target === container && isKeyboardFocus && !isTabbingBackOut) {
      const entry = new CustomEvent(ENTRY_FOCUS, { bubbles: false, cancelable: true })
      container.dispatchEvent(entry)
      if (!entry.defaultPrevented) {
        const enabled = focusable()
        const activeItem = enabled.find(isActive)
        const currentItem = enabled.find((el) => tabStopId(el) === currentId)
        focusFirst([activeItem, currentItem, ...enabled].filter(Boolean), preventScrollOnEntryFocus)
      }
    }
    isClickFocus = false
  }

  const onFocusOut = () => {
    isTabbingBackOut = false
    render()
  }

  const onKeyDown = (event) => {
    if (event.key === "Tab" && event.shiftKey && itemOf(event.target)) {
      isTabbingBackOut = true
      render()
      return
    }
    const item = event.target
    if (!all().includes(item)) return
    const intent = focusIntent(event, orientation, dirOf())
    if (intent === undefined) return
    if (event.metaKey || event.ctrlKey || event.altKey || event.shiftKey) return
    event.preventDefault()
    let candidates = focusable()
    if (intent === "last") candidates.reverse()
    else if (intent === "prev" || intent === "next") {
      if (intent === "prev") candidates.reverse()
      const index = candidates.indexOf(item)
      candidates = loop ? wrapArray(candidates, index + 1) : candidates.slice(index + 1)
    }
    setTimeout(() => focusFirst(candidates))
  }

  if (onEntryFocus) container.addEventListener(ENTRY_FOCUS, onEntryFocus)
  container.addEventListener("mousedown", onMouseDown)
  container.addEventListener("focusin", onFocusIn)
  container.addEventListener("focusout", onFocusOut)
  container.addEventListener("keydown", onKeyDown)
  const observer = new MutationObserver(render)
  observer.observe(container, { childList: true, subtree: true, attributes: true, attributeFilter: ["data-disabled"] })
  render()

  return {
    currentTabStop: () => currentId,
    setCurrentTabStop: setCurrent,
    release() {
      observer.disconnect()
      if (onEntryFocus) container.removeEventListener(ENTRY_FOCUS, onEntryFocus)
      container.removeEventListener("mousedown", onMouseDown)
      container.removeEventListener("focusin", onFocusIn)
      container.removeEventListener("focusout", onFocusOut)
      container.removeEventListener("keydown", onKeyDown)
    },
  }
}
