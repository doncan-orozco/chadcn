    # A date picker bound to the field (helper: `field.date_picker`): the Popover + outline Button + {Chadcn::Calendar} recipe of
    # docs/form-controls.md, with a hidden input named after the field. The trigger button carries the field `id` and `aria`; the
    # label shows the date in English ("March 10th, 2026") or the placeholder. The attributes you pass merge onto the button (an +id:+ you
    # pass moves the button only: the hidden input and label ids, and the calendar selectors, stay on the field id). The hidden
    # input is disabled together with the button.
    #
    # @example
    #   field.date_picker(placeholder: "Birthday", calendar: { start_month: Date.new(1990, 1, 1) })
    class DatePicker < Chadcn::Base
      include Support

      # @return [String]
      # @api private
      BUTTON_CLASS = "w-[240px] justify-start text-left font-normal has-[[data-empty=true]]:text-muted-foreground"

      # @param placeholder [String] label text while no date is selected
      # @param calendar [Hash] kwargs of {Chadcn::Calendar}, merged over the bound ones (they win)
      # @param attrs [Hash] attributes merged onto the trigger {Chadcn::Button}
      def initialize(placeholder: "Pick a date", calendar: {}, **attrs)
        @placeholder = placeholder
        @calendar = calendar
        @attrs = attrs
        super()
      end

      # @return [void]
      # @raise [ArgumentError] when the value is not a Date, Time, ISO 8601 date String or nil
      def view_template
        field = form_field
        date = date_default(field)
        value_id = "#{field.form_item_id}-value"
        label_id = "#{field.form_item_id}-label"
        button = merge_attrs({ variant: "outline", class: BUTTON_CLASS, **field.control_attrs.except(:name, :value) }, @attrs)
        calendar = { mode: :single, selected: date, input: "##{value_id}", label: "##{label_id}", close_on_select: true }.merge(@calendar)

        input(type: "hidden", id: value_id, name: field.name, value: date&.iso8601, disabled: button[:disabled])
        render Chadcn::Popover.new do
          render Chadcn::Popover::Trigger.new(as_child: Chadcn::Button.new(**button)) do
            render Chadcn::Icon.new("calendar")
            span(id: label_id, data: { chadcn__calendar_placeholder: @placeholder, empty: date.nil?.to_s }) { label_text(date) }
          end
          render Chadcn::Popover::Content.new(class: "w-auto p-0", align: "start") { render Chadcn::Calendar.new(**calendar) }
        end
      end

      private

      # date-fns "PPP" in English: "March 10th, 2026".
      def label_text(date)
        return @placeholder unless date

        ordinal = (11..13).cover?(date.day % 100) ? "th" : { 1 => "st", 2 => "nd", 3 => "rd" }.fetch(date.day % 10, "th")
        date.strftime("%B #{date.day}#{ordinal}, %Y")
      end
    end

