# frozen_string_literal: true

# shadcn `Form` (new-york-v4). Spec: dev/port/specs/form.md. Tier third_party: the react-hook-form plumbing is replaced by a
# {Chadcn::Form::Binding}.
#
# Renders the only +<form>+ and yields itself; +form.field(attribute: :email)+ renders a bound {Chadcn::Form::Field}.
# Either give a +binding:+ or let the form build a {Chadcn::Form::Binding::Plain} from +scope:+, +model:+ and +errors:+.
#
# @example
#   render Chadcn::Form.new(scope: :user, model: user, errors: { email: [ "is invalid" ] }, action: "/users") do |form|
#     form.field(attribute: :email) do |field|
#       field.label
#       field.input(type: "email")
#       field.description { "We never share it." }
#       field.error
#     end
#   end
#
# +form.fields(attribute: :address) { |address| ... }+ binds an associated object; see {Chadcn::Form#fields}.
#
# @!method field(**attrs, &block)
#   Renders {Form::Field}; same as +render Form::Field.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
class Chadcn::Form < Chadcn::Base
  # Key under which the root shares its binding with its fields through the Phlex context.
  #
  # @return [Symbol]
  # @api private
  CONTEXT_KEY = :chadcn_form_binding

  # The verbs a form accepts.
  #
  # @return [Array<String>]
  # @api private
  HTTP_METHODS = %w[get post put patch delete].freeze

  # The verbs a browser form submits natively; the others go through a hidden +_method+.
  #
  # @return [Array<String>]
  # @api private
  NATIVE_METHODS = %w[get post].freeze

  # Stimulus identifier of the controller that mirrors the browser's validity into the fields.
  #
  # @return [String]
  # @api private
  CONTROLLER = "chadcn--form"

  # Stimulus action descriptors: +invalid+ does not bubble, so it is captured. +click+ is how Checkbox, Switch and RadioGroup notify
  # their hidden native input (a synthetic bubbling click, never input/change); the controller ignores every other click.
  #
  # @return [String]
  # @api private
  ACTION = "invalid->chadcn--form#report:capture input->chadcn--form#edit change->chadcn--form#edit click->chadcn--form#edit reset->chadcn--form#reset"

  # Builds the form. +nil+ means "not given"; the Plain binding defaults the method to +"post"+ and the errors to +{}+. +class:+
  # travels in +**attrs+.
  #
  # @param binding [Chadcn::Form::Binding, nil] a binding; excludes every other kwarg below
  # @param scope [Symbol, String, Array, nil] name prefix of the Plain binding
  # @param model [Object, nil] where the Plain binding reads values (needs +scope:+)
  # @param errors [#[], nil] attribute => messages
  # @param action [String, nil]
  # @param method [String, Symbol, nil] +get+, +post+ (default), +put+, +patch+ or +delete+; the last three render +method="post"+
  #   plus a hidden +_method+
  # @param csrf_token [String, nil] rendered as a hidden +authenticity_token+ (never on a +get+ form)
  # @param namespace [String, nil] prefix of every generated id
  # @param attrs [Hash] HTML attributes merged onto the +<form>+
  # @raise [ArgumentError] when +binding:+ comes with another kwarg, +model:+ comes without +scope:+, or +method:+ is not a known verb
  def initialize(binding: nil, scope: nil, model: nil, errors: nil, action: nil, method: nil, csrf_token: nil, namespace: nil, **attrs)
    given = { scope:, model:, errors:, action:, method:, csrf_token:, namespace: }.compact
    if binding
      raise ArgumentError, "binding: cannot be combined with #{given.keys.map { |key| "#{key}:" }.join(', ')}" unless given.empty?
    elsif model && scope.nil?
      raise ArgumentError, "model: needs scope: (the name prefix of the fields)"
    end
    if method && !HTTP_METHODS.include?(method.to_s.downcase)
      raise ArgumentError, "method: must be get, post, put, patch or delete (got #{method.inspect})"
    end

    @binding = binding || Chadcn::Form::Binding::Plain.new(scope:, object: model, errors: errors || {}, action:,
                                                           http_method: method || "post", csrf_token:, namespace:)
    @attrs = attrs
    super()
  end

  # @yield [form] the form, to use +form.field+
  # @yieldparam form [Chadcn::Form]
  # @return [void]
  def view_template(&block)
    previous = context[CONTEXT_KEY]
    context[CONTEXT_KEY] = @binding
    verb = @binding.http_method.to_s.downcase
    unless HTTP_METHODS.include?(verb)
      raise ArgumentError, "#{@binding.class}#http_method must be one of #{HTTP_METHODS.join(', ')} (got #{@binding.http_method.inspect})"
    end

    html_method = verb == "get" ? "get" : "post"
    attrs = merge_attrs({ data: { slot: "form", controller: CONTROLLER, action: ACTION }, action: @binding.action, method: html_method }, @attrs)
    form(**attrs) do
      input(type: "hidden", name: "_method", value: verb) unless NATIVE_METHODS.include?(verb)
      token = @binding.csrf_token
      input(type: "hidden", name: "authenticity_token", value: token, autocomplete: "off") if token && verb != "get"
      yield self if block
    end
  ensure
    context[CONTEXT_KEY] = previous
  end

  # Binds an associated object (or each object of a collection) and yields a {Chadcn::Form::Fields} scope whose fields are named
  # like Rails nested attributes: +user[address_attributes][street]+, +user[addresses_attributes][0][street]+. An enumerable
  # (not a +Hash+ or +Struct+) yields once per element with its row; +nil+ or a single object yields once; an empty collection
  # yields nothing. After the yielded block, the hidden inputs the nested binding asks for (the +id+ of a persisted child with
  # the engine binding) are rendered, as +fields_for+ does. Scopes nest: +address.fields(attribute: :phones)+.
  #
  # @example
  #   form.fields(attribute: :addresses) do |address|
  #     address.field(attribute: :street) { |field| field.label; field.input; field.error }
  #   end
  #
  # @param attribute [Symbol, String] the association, read from the binding of the enclosing scope
  # @param index [Integer, String, nil] the row: an Integer picks that element of a collection; for a single object it is passed
  #   through to the name (+child_index:+, e.g. +"NEW_RECORD"+ for a template row)
  # @yield [fields] once per row
  # @yieldparam fields [Chadcn::Form::Fields]
  # @return [void]
  # @raise [ArgumentError] without a block, or when +index:+ does not select a row of the collection
  def fields(attribute:, index: nil, &)
    fields_of(context[CONTEXT_KEY] || @binding, attribute:, index:, &)
  end

  # {#fields} under an explicit parent binding, so a {Chadcn::Form::Fields} never depends on which binding is current.
  #
  # @param parent [Chadcn::Form::Binding]
  # @param attribute [Symbol, String]
  # @param index [Integer, String, nil]
  # @return [void]
  # @api private
  def fields_of(parent, attribute:, index: nil, &block)
    raise ArgumentError, "fields(attribute: #{attribute.inspect}) needs a block" unless block

    nested_rows(parent, attribute, index).each do |object, row|
      nested = parent.nested(attribute, object:, index: row)
      render_nested(Chadcn::Form::Fields.new(form: self, form_binding: nested), &block)
    end
  end

  # +[object, row]+ pairs of an association: every element of a collection, the one an Integer +index:+ selects, or the single object.
  #
  # @return [Array<Array>]
  def nested_rows(parent, attribute, index)
    value = parent.value_for(attribute)
    return [ [ value, index ] ] unless value.respond_to?(:each) && !value.is_a?(Hash) && !value.is_a?(Struct)
    return value.each_with_index.to_a if index.nil?

    rows = value.to_a
    unless index.is_a?(Integer) && index.between?(0, rows.size - 1)
      raise ArgumentError, "fields(attribute: #{attribute.inspect}, index: #{index.inspect}) does not select a row of the collection"
    end

    [ [ rows[index], index ] ]
  end

  # Yields the scope with its binding in the render context, then renders the hidden inputs the binding asks for.
  def render_nested(scope)
    nested = scope.form_binding
    outer = context[CONTEXT_KEY]
    context[CONTEXT_KEY] = nested
    yield scope
    nested.hidden_fields.each do |attribute, value|
      next if value.nil?

      input(type: "hidden", name: nested.name_for(attribute), id: nested.id_for(attribute), value:, autocomplete: "off")
    end
  ensure
    context[CONTEXT_KEY] = outer
  end
  private :nested_rows, :render_nested

  # The questions a bound {Chadcn::Form::Field} asks about one attribute. A binding is plain Ruby and answers all of them, so
  # the field never knows which binding it has; {Chadcn::Form::Binding::Plain} is the one core ships. Include this module and
  # override every method to write another one; the defaults raise +NotImplementedError+.
  #
  # @example
  #   class MyBinding
  #     include Chadcn::Form::Binding
  #     def name_for(attribute, multiple: false) = "x[#{attribute}]#{'[]' if multiple}"
  #     # ... the other messages
  #   end
  module Binding
    # @param attribute [Symbol, String]
    # @param multiple [Boolean] append +[]+ for a multi-value control
    # @return [String] the +name+ of the control
    def name_for(attribute, multiple: false)
      raise NotImplementedError, "#{self.class} must implement #name_for"
    end

    # @param attribute [Symbol, String]
    # @return [String] the base of the generated ids (unique per scope)
    def id_for(attribute)
      raise NotImplementedError, "#{self.class} must implement #id_for"
    end

    # @param attribute [Symbol, String]
    # @return [Object, nil] the current value
    def value_for(attribute)
      raise NotImplementedError, "#{self.class} must implement #value_for"
    end

    # @param attribute [Symbol, String]
    # @return [Array<String>] the error messages
    def errors_for(attribute)
      raise NotImplementedError, "#{self.class} must implement #errors_for"
    end

    # @param attribute [Symbol, String]
    # @return [String] the label text
    def label_for(attribute)
      raise NotImplementedError, "#{self.class} must implement #label_for"
    end

    # @param attribute [Symbol, String] the nested attribute
    # @param object [Object, nil] the nested object
    # @param index [Integer, String, nil] the row of a collection
    # @param errors [#[], nil] the errors of the nested object; +nil+ (the default, once +{}+) lets the binding find them
    # @return [Chadcn::Form::Binding] a binding for the nested object
    def nested(attribute, object:, index: nil, errors: nil)
      raise NotImplementedError, "#{self.class} must implement #nested"
    end

    NO_HIDDEN_FIELDS = {}.freeze
    private_constant :NO_HIDDEN_FIELDS

    # The hidden inputs a nested scope renders after its fields (the +id+ of a persisted child). Optional: the default is none.
    #
    # @return [Hash{Symbol, String => Object}] attribute => value; the name and id come from {#name_for} and {#id_for}
    def hidden_fields = NO_HIDDEN_FIELDS

    # @return [String, nil] the form action
    def action
      raise NotImplementedError, "#{self.class} must implement #action"
    end

    # @return [String] the HTTP method, lowercase (+"post"+, +"get"+, +"patch"+...)
    def http_method
      raise NotImplementedError, "#{self.class} must implement #http_method"
    end

    # @return [String, nil] the CSRF token, nil for none
    def csrf_token
      raise NotImplementedError, "#{self.class} must implement #csrf_token"
    end

    # A {Chadcn::Form::Binding} over plain Ruby: a scope, any object that answers the attribute readers (Struct, Hash) and an
    # errors lookup (a Hash, or anything answering +[]+ with a symbol or string key such as +ActiveModel::Errors+).
    #
    # @example
    #   Chadcn::Form::Binding::Plain.new(scope: :user, object: { email: "a@b.co" }, errors: { email: [ "is invalid" ] })
    class Plain
      include Binding

      # @return [String, nil]
      attr_reader :action
      # @return [String] lowercase
      attr_reader :http_method
      # @return [String, nil]
      attr_reader :csrf_token

      # @param scope [Symbol, String, Array<Symbol, String>, nil] the name prefix (+user+ gives +user[email]+); nil gives unscoped names
      # @param object [Struct, Hash, #public_send, nil] where values are read from
      # @param errors [#[], nil] attribute => message(s)
      # @param action [String, nil]
      # @param http_method [String, Symbol] the form method
      # @param csrf_token [String, nil]
      # @param namespace [String, nil] prefix of every id
      def initialize(scope:, object: nil, errors: {}, action: nil, http_method: "post", csrf_token: nil, namespace: nil)
        @namespace = namespace
        @path = Array(scope).map(&:to_s)
        @object = object
        @errors = errors || {}
        @action = action
        @http_method = http_method.to_s.downcase
        @csrf_token = csrf_token
      end

      # @param attribute [Symbol, String]
      # @param multiple [Boolean]
      # @return [String]
      def name_for(attribute, multiple: false)
        head, *tail = @path + [ attribute.to_s ]
        "#{head}#{tail.map { |segment| "[#{segment}]" }.join}#{'[]' if multiple}"
      end

      # @param attribute [Symbol, String]
      # @return [String]
      def id_for(attribute)
        [ @namespace, *@path, attribute.to_s ].compact.join("_")
      end

      # The attribute is read with +public_send+; never pass request input as the attribute.
      #
      # @param attribute [Symbol, String]
      # @return [Object, nil]
      def value_for(attribute)
        case @object
        when nil then nil
        when Hash then @object.fetch(attribute.to_sym) { @object[attribute.to_s] }
        else @object.public_send(attribute)
        end
      end

      # @param attribute [Symbol, String]
      # @return [Array<String>]
      def errors_for(attribute)
        Array(@errors[attribute.to_sym] || @errors[attribute.to_s]).map(&:to_s)
      end

      # @param attribute [Symbol, String]
      # @return [String] the humanized attribute (+first_name+ gives +First name+)
      def label_for(attribute)
        attribute.to_s.tr("_", " ").capitalize
      end

      # A nested binding: +user[addresses_attributes][0][street]+. Carries the namespace. Without +errors:+ the row's errors are
      # found in this binding's errors under Rails' +index_errors+ keys: +"addresses[0].street"+ (+"address.street"+ without an index).
      #
      # @param attribute [Symbol, String]
      # @param object [Object, nil]
      # @param index [Integer, String, nil]
      # @param errors [#[], nil] the errors of the nested object; +nil+ derives them from this binding's errors
      # @return [Chadcn::Form::Binding::Plain]
      def nested(attribute, object:, index: nil, errors: nil)
        errors ||= RowErrors.new(@errors, "#{attribute}#{"[#{index}]" if index}.")
        self.class.new(scope: @path + [ "#{attribute}_attributes", *index&.to_s ], object:, errors:, namespace: @namespace)
      end

      # The errors of one nested row: +[:street]+ reads +errors[:"addresses[0].street"]+ of the parent.
      class RowErrors
        # @param errors [#[]]
        # @param prefix [String] +"addresses[0]."+
        def initialize(errors, prefix)
          @errors = errors
          @prefix = prefix
        end

        # @param key [Symbol, String]
        # @return [Array<String>, nil]
        def [](key)
          full_key = "#{@prefix}#{key}"
          @errors[full_key.to_sym] || @errors[full_key]
        end
      end
      private_constant :RowErrors
    end
  end

  # The scope {Chadcn::Form#fields} yields for one nested object: it knows the nested binding and renders fields and deeper scopes
  # through the form. Its fields and deeper scopes are bound to its own binding wherever they are called.
  #
  # @example
  #   form.fields(attribute: :addresses) { |address| address.field(attribute: :street) { |field| field.input } }
  class Fields
    # @return [Chadcn::Form::Binding] the binding of the nested object
    attr_reader :form_binding

    # @param form [Chadcn::Form] the rendering form
    # @param form_binding [Chadcn::Form::Binding]
    # @api private
    def initialize(form:, form_binding:)
      @form = form
      @form_binding = form_binding
    end

    # Renders a {Chadcn::Form::Field} bound to an attribute of the nested object.
    #
    # @param attrs [Hash] as {Chadcn::Form::Field}
    # @return [void]
    def field(**attrs, &) = @form.field(binding: form_binding, **attrs, &)

    # Binds an association of the nested object; as {Chadcn::Form#fields}.
    #
    # @param attribute [Symbol, String]
    # @param index [Integer, String, nil]
    # @return [void]
    def fields(attribute:, index: nil, &) = @form.fields_of(form_binding, attribute:, index:, &)
  end

  # A field bound to one attribute of the enclosing {Chadcn::Form}'s binding (shadcn `FormField` + `FormItem`). It is a
  # {Chadcn::Field} that knows the name, value, errors and the +form.tsx+ ids of its attribute, and offers the bound parts as
  # helpers: +field.label+, +field.control+, +field.description+, +field.error+ and the controls (+field.input+, +field.textarea+,
  # +field.select+, +field.native_select+, +field.checkbox+, +field.switch+, +field.radio_group+, +field.slider+, +field.date_picker+, +field.input_group+).
  # The helpers of {Chadcn::Field} that this class does not shadow (+field.title+, +field.content+...) stay inherited.
  #
  # @example
  #   form.field(attribute: :email) do |field|
  #     field.label
  #     field.input(type: "email")
  #     field.error
  #   end
  #
  # @!method label(**attrs, &block)
  #   Renders {Form::Field::Label}; same as +render Form::Field::Label.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method control(**attrs, &block)
  #   Renders {Form::Field::Control}; same as +render Form::Field::Control.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method description(**attrs, &block)
  #   Renders {Form::Field::Description}; same as +render Form::Field::Description.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method error(**attrs, &block)
  #   Renders {Form::Field::Error}; same as +render Form::Field::Error.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method input(**attrs, &block)
  #   Renders {Form::Field::Input}; same as +render Form::Field::Input.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method textarea(**attrs, &block)
  #   Renders {Form::Field::Textarea}; same as +render Form::Field::Textarea.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method select(**attrs, &block)
  #   Renders {Form::Field::Select}; same as +render Form::Field::Select.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method native_select(**attrs, &block)
  #   Renders {Form::Field::NativeSelect}; same as +render Form::Field::NativeSelect.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method checkbox(**attrs, &block)
  #   Renders {Form::Field::Checkbox}; same as +render Form::Field::Checkbox.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method switch(**attrs, &block)
  #   Renders {Form::Field::Switch}; same as +render Form::Field::Switch.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method radio_group(**attrs, &block)
  #   Renders {Form::Field::RadioGroup}; same as +render Form::Field::RadioGroup.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method slider(**attrs, &block)
  #   Renders {Form::Field::Slider}; same as +render Form::Field::Slider.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method date_picker(**attrs, &block)
  #   Renders {Form::Field::DatePicker}; same as +render Form::Field::DatePicker.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  #
  # @!method input_group(**attrs, &block)
  #   Renders {Form::Field::InputGroup}; same as +render Form::Field::InputGroup.new(**attrs), &block+. Generated by +Base.const_added+.
  #   @return [void]
  class Field < Chadcn::Field
    # Key under which the field shares itself with its parts through the Phlex context.
    #
    # @return [Symbol]
    # @api private
    FIELD_KEY = :chadcn_form_field

    # @return [Symbol, String] the bound attribute
    attr_reader :attribute

    # @param attribute [Symbol, String] the attribute of the binding
    # @param binding [Chadcn::Form::Binding, nil] nil means the enclosing form's, read from the render context
    # @param orientation [String, Symbol, nil] as {Chadcn::Field}
    # @param attrs [Hash] HTML attributes merged onto the root +<div>+
    def initialize(attribute:, binding: nil, orientation: "vertical", **attrs)
      @attribute = attribute
      @given_binding = binding
      super(orientation:, **attrs)
    end

    # The binding, resolved at render time.
    #
    # @return [Chadcn::Form::Binding]
    # @raise [ArgumentError] outside a {Chadcn::Form} without +binding:+
    def form_binding
      @form_binding ||= @given_binding || context[CONTEXT_KEY] ||
                        raise(ArgumentError, "Chadcn::Form::Field must be rendered inside Chadcn::Form or given binding:")
    end

    # @return [String] the +name+ of the control
    def name = form_binding.name_for(attribute)

    # @return [Object, nil] the current value
    def value = form_binding.value_for(attribute)

    # @return [Array<String>] the error messages
    def errors = (@errors ||= form_binding.errors_for(attribute).freeze)

    # @return [String] id of the control and +for+ of the label
    def form_item_id = "#{form_binding.id_for(attribute)}-form-item"

    # @return [String] id of the description
    def form_description_id = "#{form_item_id}-description"

    # @return [String] id of the error message
    def form_message_id = "#{form_item_id}-message"

    # The attributes a bound control receives.
    #
    # @return [Hash] +name+, +id+, +value+ and +aria+ (+invalid+, +describedby+)
    def control_attrs
      invalid = errors.any?
      describedby = invalid ? "#{form_description_id} #{form_message_id}" : form_description_id
      { name:, id: form_item_id, value:, aria: { invalid: invalid.to_s, describedby: } }
    end

    # @yield [field] the field itself
    # @yieldparam field [Chadcn::Form::Field]
    # @return [void]
    # @raise [ArgumentError] outside a {Chadcn::Form} without +binding:+
    def view_template(&)
      previous = context[FIELD_KEY]
      form_binding
      context[FIELD_KEY] = self
      @attrs = merge_attrs({ data: { invalid: "true" } }, @attrs) if errors.any?
      super
    ensure
      context[FIELD_KEY] = previous
    end

    # Reads the enclosing {Chadcn::Form::Field} from the render context for the parts of a bound field, and holds the value casts
    # of the bound controls (+option_default+, +date_default+, +raise_value_error+).
    #
    # @api private
    module Support
      private

      # @return [Chadcn::Form::Field]
      # @raise [ArgumentError] when rendered outside a {Chadcn::Form::Field}
      def form_field
        context[FIELD_KEY] ||
          raise(ArgumentError, "#{self.class.name} must be rendered inside Chadcn::Form::Field")
      end

      # The bound value as the String of an uncontrolled option control (+nil+ stays +nil+); +many+ also accepts an Array.
      #
      # @return [String, Array<String>, nil]
      # @raise [ArgumentError] for a value the control cannot express
      def option_default(field, many: false)
        value = field.value
        return value.map { |item| option_default_of(field, item) } if many && value.is_a?(Array)

        option_default_of(field, value)
      end

      def option_default_of(field, value)
        return value&.to_s if value.nil? || value.is_a?(String) || value.is_a?(Symbol) || value.is_a?(Integer)

        raise_value_error(field, "must be a String, Symbol, Integer or nil", value)
      end

      # @return [Date, nil] the bound value as a date
      # @raise [ArgumentError] when it is not a Date, a Time, an ISO 8601 date String or nil
      def date_default(field)
        value = field.value
        case value
        when nil then nil
        when Date, Time then value.to_date
        when String then value.empty? ? nil : Date.iso8601(value)
        else raise_value_error(field, "must be a Date, a Time or an ISO 8601 date String", value)
        end
      rescue Date::Error
        raise_value_error(field, "must be a Date, a Time or an ISO 8601 date String", value)
      end

      def raise_value_error(field, expected, value)
        raise ArgumentError, "#{self.class.name}: value for #{field.attribute.to_sym.inspect} #{expected} (got #{value.class})"
      end
    end

