    # Shared by {Checkbox} and {Switch}: the hidden unchecked input, the checked cast and the bound render. The including class sets
    # +@attrs+ and +@unchecked_value+ in its +initialize+.
    #
    # @api private
    module Toggleable
      include Support

      # @api private
      CHECKED = [ true, 1, "1", "true", "t", "on", "yes" ].freeze
      # @api private
      UNCHECKED = [ nil, false, 0, "0", "false", "f", "off", "no", "" ].freeze
      private_constant :CHECKED, :UNCHECKED

      private

      def render_toggle(component)
        field = form_field
        box = @attrs.fetch(:value, "1").to_s
        bound = field.control_attrs.except(:value).merge(value: "1", default_checked: checked?(field, box))
        attrs = merge_attrs(bound, @attrs)
        render_unchecked_input(attrs) unless @unchecked_value.nil?
        render component.new(**attrs)
      end

      def render_unchecked_input(attrs)
        input(type: "hidden", name: attrs[:name], value: @unchecked_value.to_s, autocomplete: "off", form: attrs[:form], disabled: attrs[:disabled])
      end

      def checked?(field, box)
        value = field.value
        value = value.downcase if value.is_a?(String) && value != box
        return true if (value.is_a?(String) && value == box) || CHECKED.include?(value)
        return false if UNCHECKED.include?(value)

        raise_value_error(field, "must be true, false, 0, 1, a boolean-like String (\"on\", \"off\"...), the checkbox value or nil", value)
      end
    end

