# frozen_string_literal: true

# shadcn DropdownMenu (Radix DropdownMenu + Menu). Spec: port spec (dev kit).
# Behavior lives in controllers/chadcn/dropdown_menu_controller.js (hosted by the Trigger).
#
# Root, Sub and Portal render no element: they push their state into the Phlex render context for the parts inside.
# Radix mounts Content/SubContent only while open, so those parts ship their markup in an inert <template> that the
# controller clones through the template_mount primitive.
#
# The parts are nested classes (+DropdownMenu::Item+, +DropdownMenu::SubContent+...); the root yields itself and exposes a
# helper per part, so +menu.item { "Profile" }+ is the same as +render DropdownMenu::Item.new { "Profile" }+.
#
# Events and focus. All events are named +chadcn--dropdown-menu:<name>+. The root's +open-change+ (+detail.open+) is
# dispatched on the Trigger; a Sub's +open-change+ is dispatched with the SubTrigger as target. +select+ (cancelable,
# on the item), +checked-change+ (+detail.checked+) and +value-change+ (+detail.value+) are dispatched on the item. The
# content dispatches the cancelable +escape-key-down+, +pointer-down-outside+, +focus-outside+ and +interact-outside+
# (+detail.originalEvent+): +preventDefault+ keeps the menu from dismissing. +open-auto-focus+ and +close-auto-focus+ are
# cancelable too: +preventDefault+ skips focusing the content on open / returning focus to the Trigger on close. In a
# controlled menu the caller reacts to +open-change+ and re-renders with the new +open:+.
#
# @example Uncontrolled menu
#   render Chadcn::DropdownMenu.new do |menu|
#     menu.trigger { "Open" }
#     menu.content do
#       menu.label { "My account" }
#       menu.separator
#       menu.item { "Profile" }
#       menu.item(variant: "destructive") { "Delete" }
#       menu.sub do
#         menu.sub_trigger { "More" }
#         menu.sub_content { menu.item { "Export" } }
#       end
#     end
#   end
#
# @example Controlled menu with a radio group
#   render Chadcn::DropdownMenu.new(open: @open) do |menu|
#     menu.trigger { "Sort" }
#     menu.content do
#       menu.radio_group(value: @sort) do
#         menu.radio_item(value: "asc") { "Ascending" }
#         menu.radio_item(value: "desc") { "Descending" }
#       end
#     end
#   end
#
# @example Item with a shortcut
#   menu.item do
#     plain "Save"
#     menu.shortcut { "Ctrl+S" }
#   end
#
# @!method portal(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Portal.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method trigger(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Trigger.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method content(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Content.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method group(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Group.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method label(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Label.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method item(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Item.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method checkbox_item(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::CheckboxItem.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method radio_group(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::RadioGroup.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method radio_item(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::RadioItem.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method separator(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Separator.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method shortcut(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Shortcut.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method sub(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::Sub.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method sub_trigger(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::SubTrigger.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
#
# @!method sub_content(**attrs, &block)
#   Sugar for +render Chadcn::DropdownMenu::SubContent.new(**attrs), &block+ (generated by Base.const_added).
#   @return [void]
class Chadcn::DropdownMenu < Chadcn::Base
  include Chadcn::Direction::Consumer

  # Render context key of the root state.
  #
  # @api private
  # @return [Symbol]
  ROOT_KEY = :shadcn_dropdown_menu_root
  # Render context key of the current Sub state.
  #
  # @api private
  # @return [Symbol]
  SUB_KEY = :shadcn_dropdown_menu_sub
  # Render context key of the enclosing Portal options.
  #
  # @api private
  # @return [Symbol]
  PORTAL_KEY = :shadcn_dropdown_menu_portal
  # Render context key of the current RadioGroup value.
  #
  # @api private
  # @return [Symbol]
  RADIO_GROUP_KEY = :shadcn_dropdown_menu_radio_group
  # Render context key of the id counter (per request with the engine, per render without it, see Chadcn::Sequence).
  #
  # @api private
  # @return [Symbol]
  SEQUENCE_KEY = :shadcn_dropdown_menu_sequence
  # Accepted values of +dir:+.
  #
  # @api private
  # @return [Array<String>]
  DIRECTIONS = %w[ltr rtl].freeze

  # Unknown keywords raise ArgumentError at construction.
  #
  # @param open [Boolean, nil] non-nil makes the menu controlled: the server decides the state and user actions only
  #   dispatch +open-change+. +nil+ (default) leaves the state to the controller.
  # @param default_open [Boolean] initial state when uncontrolled (default +false+); ignored when +open:+ is given
  # @param modal [Boolean] default +true+; rendered as the controller's modal value (outside pointer events and scroll
  #   are blocked while open)
  # @param dir [String, Symbol, nil] +"ltr"+ or +"rtl"+. Any other value (and +nil+) is ignored without error and the
  #   direction comes from the nearest Direction::Provider, then +"ltr"+.
  # @param id [String, nil] id of the content (what the trigger controls); the trigger is "<id>-trigger", the subs "<id>-sub-N"
  #   with triggers "<id>-sub-N-trigger". Default `dropdown-menu-N`, numbered per request with the engine, per render without it
  # @raise [ArgumentError] when id: is empty or contains whitespace, a double quote or a backslash
  # @return [void]
  def initialize(open: nil, default_open: false, modal: true, dir: nil, id: nil)
    @controlled = !open.nil?
    @open = @controlled ? open : default_open
    @modal = modal
    @dir = dir.to_s if DIRECTIONS.include?(dir.to_s)
    @id = validated_id(id)
    super()
  end

  # Registers the root state for the parts inside and yields self (for the part helpers).
  #
  # @yieldparam menu [Chadcn::DropdownMenu] this root, which responds to a helper per part
  # @return [void]
  def view_template
    previous = context[ROOT_KEY]
    base = @id || "dropdown-menu-#{next_sequence(SEQUENCE_KEY)}"
    context[ROOT_KEY] = {
      content_id: base, trigger_id: "#{base}-trigger", base:, subs: 0,
      open: @open, controlled: @controlled, modal: @modal, dir: use_direction(@dir)
    }
    yield self if block_given?
  ensure
    context[ROOT_KEY] = previous
  end
end
