# frozen_string_literal: true

# shadcn RadioGroup over Radix RadioGroup. Spec: docs/shadcn-port/specs/radio-group.md.
# Behavior: controllers/shadcn/radio_group_controller.js (one controller per group, items are not controllers).
#
# Yields itself, so items are available as `group.item(value: "a")` (see {RadioGroup::Item}).
#
# @example
#   render Chadcn::RadioGroup.new(name: "plan", default_value: "pro") do |group|
#     group.item(value: "free", id: "plan-free")
#     group.item(value: "pro", id: "plan-pro")
#   end
#
# @!method item(value:, **attrs, &block)
#   Renders {RadioGroup::Item}; same as +render RadioGroup::Item.new(value:, **attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
class Chadcn::RadioGroup < Chadcn::Base
  include Chadcn::Direction::Consumer

  # Key under which the root shares its state with its items through the Phlex context.
  #
  # @api private
  ROOT_KEY = :shadcn_radio_group_root
  # Classes of the root element.
  # @return [String]
  #
  # @api private
  CLASSES = "grid gap-3"
  # Allowed values of `orientation:`.
  # @return [Array<String>]
  ORIENTATIONS = %w[horizontal vertical].freeze
  # Allowed values of `dir:`.
  # @return [Array<String>]
  DIRECTIONS = %w[ltr rtl].freeze

  # Creates a radio group. A non-nil `value:` makes it controlled: user actions only dispatch value-change and the
  # caller re-renders with the new value.
  #
  # @param value [String, nil] controlled checked value; non-nil makes the group controlled
  # @param default_value [String, nil] initially checked value (uncontrolled)
  # @param disabled [Boolean] disables every item
  # @param required [Boolean] marks the group required (aria and bubble inputs)
  # @param name [String, nil] form field name of the bubble inputs
  # @param form [String, nil] id of the associated `<form>`
  # @param orientation [String, Symbol, nil] one of {ORIENTATIONS}
  # @param dir [String, Symbol, nil] one of {DIRECTIONS}; defaults to the surrounding direction provider
  # @param loop [Boolean] whether arrow-key focus wraps around
  # @param as_child [false, Symbol, String, Chadcn::Base] a tag or component instance to render instead of the `<div>`; false renders the default element
  # @param attrs [Hash] HTML attributes for the root (`class:` merged last)
  # @raise [ArgumentError] when `orientation:` or `dir:` is not an allowed value
  def initialize(value: nil, default_value: nil, disabled: false, required: false, name: nil, form: nil,
                 orientation: nil, dir: nil, loop: true, as_child: false, **attrs)
    @controlled = !value.nil?
    @value = (@controlled ? value : default_value)&.to_s
    @disabled = disabled
    @required = required
    @name = name
    @form = form
    @orientation = choice(orientation, ORIENTATIONS, "orientation")
    @dir = choice(dir, DIRECTIONS, "dir")
    @loop = loop
    @as_child = as_child
    @attrs = attrs
    super()
  end

  # @yield [group] optional block that renders the items
  # @yieldparam group [RadioGroup] this component, exposing the `item` helper
  # @return [void]
  def view_template
    previous = context[ROOT_KEY]
    @dir = use_direction(@dir)
    context[ROOT_KEY] = { value: @value, disabled: @disabled, required: @required, name: @name, form: @form, orientation: @orientation }
    attrs = merge_attrs(root_defaults, @attrs)
    attrs[:style] = merge_styles(root_defaults[:style], @attrs[:style]) if @attrs[:style]
    content = proc { yield self if block_given? }
    @as_child ? render_as_child(@as_child, **attrs, &content) : div(**attrs, &content)
  ensure
    context[ROOT_KEY] = previous
  end

  private

  def choice(value, allowed, name)
    return if value.nil?

    value = value.to_s
    return value if allowed.include?(value)

    raise ArgumentError, "#{name} must be one of #{allowed.join(', ')}, got #{value.inspect}"
  end

  def root_defaults
    {
      role: "radiogroup",
      aria: { required: @required.to_s, orientation: @orientation },
      dir: @dir,
      tabindex: @disabled ? -1 : 0,
      style: "outline: none;",
      class: CLASSES,
      data: {
        slot: "radio-group", orientation: @orientation, controller: "shadcn--radio-group",
        disabled: (@disabled ? "" : nil),
        shadcn__radio_group_controlled_value: @controlled.to_s,
        shadcn__radio_group_loop_value: @loop.to_s,
        shadcn__radio_group_orientation_value: @orientation,
        shadcn__radio_group_dir_value: @dir,
        shadcn__radio_group_indicator_html_value: indicator_html
      }
    }
  end

  # The controller mounts this markup when an item becomes checked (Radix Presence).
  def indicator_html
    capture { render Chadcn::RadioGroup::Item::Indicator.new(state: "checked") }
  end
end
