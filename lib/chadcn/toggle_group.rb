# frozen_string_literal: true

# shadcn ToggleGroup over Radix ToggleGroup. Spec: docs/shadcn-port/specs/toggle-group.md.
# Behavior: controllers/shadcn/toggle_group_controller.js (one controller per group, items are not controllers).
#
# A group of {ToggleGroup::Item}s sharing `type`, `variant`, `size` and `spacing`. Yields itself, so items are
# available as `group.item(value: "bold")`.
#
# @example
#   render Chadcn::ToggleGroup.new(type: :multiple, variant: :outline, default_value: [ "bold" ]) do |group|
#     group.item(value: "bold", aria: { label: "Bold" }) { "B" }
#     group.item(value: "italic", aria: { label: "Italic" }) { "I" }
#   end
#
# @!method item(value:, **attrs, &block)
#   Renders {ToggleGroup::Item}; same as +render ToggleGroup::Item.new(value:, **attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
class Chadcn::ToggleGroup < Chadcn::Base
  include Chadcn::Direction::Consumer

  # Key under which the root shares its state with its items through the Phlex context.
  #
  # @api private
  ROOT_KEY = :shadcn_toggle_group_root
  # Classes of the root element.
  #
  # @return [String]
  #
  # @api private
  CLASSES = "group/toggle-group flex w-fit items-center gap-[--spacing(var(--gap))] rounded-md data-[spacing=default]:data-[variant=outline]:shadow-xs"
  # Allowed values of `type:`.
  #
  # @return [Array<String>]
  TYPES = %w[single multiple].freeze
  # Allowed values of `orientation:`.
  #
  # @return [Array<String>]
  ORIENTATIONS = %w[horizontal vertical].freeze
  # Allowed values of `dir:`.
  #
  # @return [Array<String>]
  DIRECTIONS = %w[ltr rtl].freeze

  # A non-nil `value:` makes the group controlled: user actions only dispatch value-change and the caller re-renders
  # with the new value.
  #
  # @param type [String, Symbol] one of {TYPES}: `single` (radio-like) or `multiple` (toolbar)
  # @param value [String, Array<String>, nil] controlled pressed value (Array for `multiple`)
  # @param default_value [String, Array<String>, nil] initially pressed value(s) (uncontrolled)
  # @param variant [String, Symbol, nil] `"default"` or `"outline"`, applied to every item; not validated here, an
  #   unknown value raises ArgumentError when an item renders (via `Toggle.variants`)
  # @param size [String, Symbol, nil] `"default"`, `"sm"` or `"lg"`, applied to every item; not validated here, an
  #   unknown value raises ArgumentError when an item renders (via `Toggle.variants`)
  # @param spacing [Numeric] gap between items in spacing units; 0 joins the items
  # @param disabled [Boolean] disables every item
  # @param roving_focus [Boolean] arrow-key navigation with a single tab stop
  # @param orientation [String, Symbol, nil] one of {ORIENTATIONS}; `data-orientation` is emitted on the root and the items
  #   only when `roving_focus` is true
  # @param dir [String, Symbol, nil] one of {DIRECTIONS}; defaults to the surrounding direction provider
  # @param loop [Boolean] whether arrow-key focus wraps around
  # @param as_child [false, Symbol, String, Chadcn::Base]
  #   a tag (`:section`) or component instance to render instead of the `<div>`; false renders the default element
  # @param attrs [Hash] HTML attributes for the root (`class:` merged last); a caller `style:` replaces the default `--gap` declaration
  # @see Chadcn::ToggleGroup::Item
  # @raise [ArgumentError] when `type:` is missing/unknown, `spacing:` is not Numeric, `value:` does not fit `type:`,
  #   or `orientation:`/`dir:` is not an allowed value
  def initialize(type:, value: nil, default_value: nil, variant: nil, size: nil, spacing: 0, disabled: false,
                 roving_focus: true, orientation: nil, dir: nil, loop: true, as_child: false, **attrs)
    @type = choice(type, TYPES, "type") or raise ArgumentError, "type is required, one of #{TYPES.join(', ')}"
    @controlled = !value.nil?
    @value = initial_value(@controlled ? value : default_value)
    @variant = normalize_option(variant)
    @size = normalize_option(size)
    raise ArgumentError, "spacing must be a Numeric, got #{spacing.inspect}" unless spacing.is_a?(Numeric)

    @spacing = format_number(spacing)
    @disabled = disabled
    @roving_focus = roving_focus
    @orientation = choice(orientation, ORIENTATIONS, "orientation")
    @dir = choice(dir, DIRECTIONS, "dir")
    @loop = loop
    @as_child = as_child
    @attrs = attrs
    super()
  end

  # @yield [group] the block that renders the items
  # @yieldparam group [Chadcn::ToggleGroup] this component, exposing the `item` helper
  # @return [void]
  def view_template
    previous = context[ROOT_KEY]
    @dir = use_direction(@dir)
    context[ROOT_KEY] = { type: @type, value: @value, variant: @variant, size: @size, spacing: @spacing,
                          disabled: @disabled, roving: @roving_focus, orientation: @orientation }
    attrs = merge_attrs(root_defaults, @attrs.except(:style))
    attrs[:style] = style
    content = proc { yield self if block_given? }
    @as_child ? render_as_child(@as_child, **attrs, &content) : div(**attrs, &content)
  ensure
    context[ROOT_KEY] = previous
  end

  private

  def choice(value, allowed, name)
    return if value.nil?

    value = value.to_s
    return value if allowed.include?(value)

    raise ArgumentError, "#{name} must be one of #{allowed.join(', ')}, got #{value.inspect}"
  end

  # single: String ("" = none); multiple: Array of Strings in activation order.
  def initial_value(value)
    if @type == "single"
      raise ArgumentError, "value must not be an Array for type #{@type}" if value.is_a?(Array)

      value.to_s
    else
      raise ArgumentError, "value must be an Array for type #{@type}" if !value.nil? && !value.is_a?(Array)

      Array(value).map(&:to_s)
    end
  end

  # JavaScript number formatting: 2.0 renders as "2".
  def format_number(number)
    (number.to_f % 1).zero? ? number.to_i.to_s : number.to_s
  end

  # Radix outline:none, then shadcn --gap; a caller style replaces the --gap declaration.
  def style
    custom = @attrs[:style]
    "#{[ (@roving_focus ? 'outline: none' : nil), (custom ? style_string(custom) : "--gap: #{@spacing}") ].compact.join('; ')};"
  end

  def root_defaults
    {
      role: (@type == "single" ? "radiogroup" : "toolbar"),
      dir: @dir,
      class: CLASSES,
      data: {
        slot: "toggle-group", variant: @variant, size: @size, spacing: @spacing, controller: "shadcn--toggle-group",
        orientation: (@roving_focus ? @orientation : nil),
        shadcn__toggle_group_type_value: @type,
        shadcn__toggle_group_controlled_value: @controlled.to_s,
        shadcn__toggle_group_initial_value: (@type == "multiple" ? json(@value) : nil),
        shadcn__toggle_group_loop_value: @loop.to_s,
        shadcn__toggle_group_roving_focus_value: @roving_focus.to_s,
        shadcn__toggle_group_orientation_value: @orientation,
        shadcn__toggle_group_dir_value: @dir
      }
    }.merge(if @roving_focus
              { tabindex: (@disabled ? -1 : 0) }
            else
              {}
            end)
  end
end
