# frozen_string_literal: true

# shadcn Menubar over Radix Menubar + Menu: a horizontal bar of menus, each opened from a {Trigger}.
# Spec: port spec (dev kit). Behavior lives in controllers/chadcn/menubar_controller.js (hosted by the
# root, one controller for every menu and sub).
#
# Menu, Sub and Portal render no element: they push their state into the Phlex render context for the parts inside.
# Radix mounts Content/SubContent only while open, so those parts ship their markup in an inert <template> that the
# controller clones into the page while the menu is open.
#
# Parts must be rendered inside the right ancestor, otherwise they raise +ArgumentError+ when they are rendered (never
# when they are constructed): Menu, Sub and Content need a Menubar, Trigger and Content need a Menu, SubTrigger and
# SubContent need a Sub.
#
# The root renders +role="menubar"+ and the controller dispatches Stimulus events (prefixed +chadcn--menubar:+). Each event
# is dispatched on the element that names it, not always on the root: the root content is mounted in +<body>+ (a portaled
# SubContent goes to its Portal container, else +<body>+), so an event fired on an item never bubbles to the root and a
# +data-action+ on the root does not see it. Listen on the item itself, on +document+ or on +window+.
#
#   | event            | dispatched on                    | detail                                              |
#   |------------------|----------------------------------|-----------------------------------------------------|
#   | value-change     | the root element                 | +value+: the menu the user asked to open, empty when closing |
#   | open-change      | the {SubTrigger}                 | +open+: the sub menu state asked for                |
#   | select           | the chosen item (cancelable)     | none                                                |
#   | checked-change   | the {CheckboxItem}               | +checked+: the new state                            |
#   | value-change     | the chosen {RadioItem}           | +value+: the item's value                           |
#
# +select+ is cancelable; +checked-change+ and the radio +value-change+ are not.
#
# The cancelable events the primitives raise are re-emitted too, on the content element (the Content, or the SubContent
# for sub menus): +escape-key-down+, +pointer-down-outside+, +focus-outside+ and +interact-outside+ (each with
# +detail.originalEvent+; preventing one keeps the menu from dismissing), plus +open-auto-focus+ and +close-auto-focus+
# on the root content only. The controller's tunable Stimulus values +sub-open-delay+ (ms, default 100),
# +pointer-grace-timeout+ (ms, default 300) and +typeahead-timeout+ (ms, default 1000) can be passed through +data:+.
#
# @example A menubar with a menu, a checkbox, a radio group and a sub menu
#   render Chadcn::Menubar.new do |bar|
#     bar.menu(value: "file") do
#       bar.trigger { "File" }
#       bar.content do
#         bar.item { "New" }
#         bar.separator
#         bar.checkbox_item(checked: true) { "Show toolbar" }
#         bar.radio_group(value: "list") do
#           bar.radio_item(value: "list") { "List" }
#           bar.radio_item(value: "grid") { "Grid" }
#         end
#         bar.sub do
#           bar.sub_trigger { "Share" }
#           bar.sub_content { bar.item { "Email" } }
#         end
#       end
#     end
#   end
#
# @!method portal(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Portal.new(**attrs), &block+. Generated by Base.const_added for every nested part (same for
#   the helpers below).
#   @return [void]
# @!method menu(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Menu.new(**attrs), &block+.
#   @return [void]
# @!method trigger(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Trigger.new(**attrs), &block+.
#   @return [void]
# @!method content(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Content.new(**attrs), &block+.
#   @return [void]
# @!method group(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Group.new(**attrs), &block+.
#   @return [void]
# @!method separator(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Separator.new(**attrs), &block+.
#   @return [void]
# @!method label(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Label.new(**attrs), &block+.
#   @return [void]
# @!method item(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Item.new(**attrs), &block+.
#   @return [void]
# @!method shortcut(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Shortcut.new(**attrs), &block+.
#   @return [void]
# @!method checkbox_item(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::CheckboxItem.new(**attrs), &block+.
#   @return [void]
# @!method radio_group(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::RadioGroup.new(**attrs), &block+.
#   @return [void]
# @!method radio_item(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::RadioItem.new(**attrs), &block+.
#   @return [void]
# @!method sub(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::Sub.new(**attrs), &block+.
#   @return [void]
# @!method sub_trigger(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::SubTrigger.new(**attrs), &block+.
#   @return [void]
# @!method sub_content(**attrs, &block)
#   Sugar for +render Chadcn::Menubar::SubContent.new(**attrs), &block+.
#   @return [void]
class Chadcn::Menubar < Chadcn::Base
  include Chadcn::Direction::Consumer

  # @api private
  # @return [Symbol] render-context key holding the root state (id base, value, direction and the menus/subs counters)
  ROOT_KEY = :shadcn_menubar_root
  # @api private
  # @return [Symbol] render-context key holding the current Menu state
  MENU_KEY = :shadcn_menubar_menu
  # @api private
  # @return [Symbol] render-context key holding the current Sub state
  SUB_KEY = :shadcn_menubar_sub
  # @api private
  # @return [Symbol] render-context key holding the current Portal state
  PORTAL_KEY = :shadcn_menubar_portal
  # @api private
  # @return [Symbol] render-context key holding the current RadioGroup value
  RADIO_GROUP_KEY = :shadcn_menubar_radio_group
  # @api private
  # @return [Symbol] render-context key of the id counter (per request with the engine, per render without it, see Chadcn::Sequence)
  SEQUENCE_KEY = :shadcn_menubar_sequence
  # @api private
  # @return [Array<String>] the accepted +dir:+ values; anything else is ignored (the Direction provider, else +ltr+, applies)
  DIRECTIONS = %w[ltr rtl].freeze
  # @return [String] default Tailwind classes of the bar; the +class:+ you pass is merged on top (conflicts resolve to yours)
  CLASSES = "flex h-9 items-center gap-1 rounded-md border bg-background p-1 shadow-xs"

  # @param value [String, Symbol, nil] the open menu (a Menu +value:+); non-nil makes the root controlled: the server
  #   decides the open menu and user actions only dispatch +value-change+. Default +nil+ (uncontrolled)
  # @param default_value [String, Symbol, nil] the menu open at first render when uncontrolled. Default +nil+ (all closed)
  # @param loop [Boolean] whether arrow-key navigation among the triggers wraps around. Default +true+
  # @param dir [String, Symbol, nil] +"ltr"+ or +"rtl"+; any other value is ignored and the Direction provider (else
  #   +ltr+) applies. It is not rendered as a +dir+ attribute
  # @param as_child [false, Symbol, String, Chadcn::Base] +false+ renders the default +div+; a tag Symbol/String
  #   or a component instance renders that element carrying the bar attributes instead
  # @param id [String, nil] id of the root element, as in React, and the base of the generated ids (`"bar-menu-1-trigger"`).
  #   Without it the element has no id and the base is `menubar-N`, numbered per request with the engine, per render without it
  # @param attrs [Hash] extra HTML attributes; +class+ is merged with {CLASSES}, +data+/+aria+ are deep merged (yours win)
  # @raise [ArgumentError] when id: is empty or contains whitespace, a double quote or a backslash
  def initialize(value: nil, default_value: nil, loop: true, dir: nil, as_child: false, id: nil, **attrs)
    @controlled = !value.nil?
    @value = (@controlled ? value : default_value).to_s
    @loop = loop
    @dir = dir.to_s if DIRECTIONS.include?(dir.to_s)
    @as_child = as_child
    @id = validated_id(id)
    @attrs = attrs
    super()
  end

  # @yieldparam bar [Chadcn::Menubar] the root, whose generated helpers (+bar.menu+, +bar.item+...) render the parts
  # @return [void]
  def view_template(&)
    previous = context[ROOT_KEY]
    root = { base: @id || "menubar-#{next_sequence(SEQUENCE_KEY)}", menus: 0, subs: 0, value: @value, dir: use_direction(@dir) }
    context[ROOT_KEY] = root
    attrs = merge_attrs({
                          id: @id, role: "menubar", class: CLASSES, tabindex: "0", style: "outline: none",
                          data: {
                            slot: "menubar", orientation: "horizontal", controller: "chadcn--menubar",
                            chadcn__menubar_value_value: @value, chadcn__menubar_controlled_value: @controlled.to_s,
                            chadcn__menubar_loop_value: @loop.to_s, chadcn__menubar_dir_value: root[:dir]
                          }
                        }, @attrs)
    if @as_child
      render_as_child(@as_child, **attrs) { yield self if block_given? }
    else
      div(**attrs) { yield self if block_given? }
    end
  ensure
    context[ROOT_KEY] = previous
  end
end
