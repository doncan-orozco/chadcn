# frozen_string_literal: true

# shadcn NativeSelect (new-york-v4). Spec: docs/shadcn-port/specs/native-select.md
#
# A styled native `<select>` inside a wrapper with a chevron icon. Yields itself, so the parts are
# available as `select.option { }` and `select.opt_group { }` (see {NativeSelect::Option}, {NativeSelect::OptGroup}).
#
# @example
#   render Chadcn::NativeSelect.new(name: "role", default_value: "editor", aria: { label: "Role" }) do |select|
#     select.option(value: "author") { "Author" }
#     select.opt_group(label: "Staff") do
#       select.option(value: "editor") { "Editor" }
#     end
#   end
#
# @!method option(**attrs, &block)
#   Renders {NativeSelect::Option}; same as +render NativeSelect::Option.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method opt_group(**attrs, &block)
#   Renders {NativeSelect::OptGroup}; same as +render NativeSelect::OptGroup.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
class Chadcn::NativeSelect < Chadcn::Base
  # Key under which the root shares the selected values with its options through the Phlex context.
  #
  # @api private
  CONTEXT_KEY = :shadcn_native_select_selected
  # Classes of the `<select>` element.
  # @return [String]
  #
  # @api private
  BASE = "h-9 w-full min-w-0 appearance-none rounded-md border border-input bg-transparent px-3 py-2 pr-9 text-sm shadow-xs transition-[color,box-shadow] outline-none selection:bg-primary selection:text-primary-foreground placeholder:text-muted-foreground disabled:pointer-events-none disabled:cursor-not-allowed data-[size=sm]:h-8 data-[size=sm]:py-1 dark:bg-input/30 dark:hover:bg-input/50"
  # Focus ring classes of the `<select>`.
  # @return [String]
  #
  # @api private
  FOCUS = "focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50"
  # `aria-invalid` classes of the `<select>`.
  # @return [String]
  #
  # @api private
  INVALID = "aria-invalid:border-destructive aria-invalid:ring-destructive/20 dark:aria-invalid:ring-destructive/40"
  # Classes of the wrapper `<div>`.
  # @return [String]
  #
  # @api private
  WRAPPER = "group/native-select relative w-fit has-[select:disabled]:opacity-50"
  # Classes of the chevron icon.
  # @return [String]
  #
  # @api private
  ICON = "pointer-events-none absolute top-1/2 right-3.5 size-4 -translate-y-1/2 text-muted-foreground opacity-50 select-none"

  # Builds the select. `value:` wins over `default_value:`; both render the `selected` attribute (spec Deviations).
  #
  # @param size [String, Symbol] `"default"` or `"sm"`, rendered as `data-size`; other values are rendered as-is in `data-size`
  # @param default_value [String, Array<String>, nil] value(s) whose options render `selected`
  # @param value [String, Array<String>, nil] same as `default_value`, takes precedence when not nil
  # @param attrs [Hash] HTML attributes for the `<select>` (`name:`, `multiple:`, `class:` merged last, `aria:`, `data:`)
  def initialize(size: "default", default_value: nil, value: nil, **attrs)
    @size = size.to_s
    @selected = Array(value.nil? ? default_value : value).map(&:to_s)
    @multiple = attrs[:multiple]
    @attrs = attrs
    super()
  end

  # @yield [select] (required) the block that renders the options
  # @yieldparam select [NativeSelect] this component, exposing the `option` and `opt_group` helpers
  # @return [void]
  def view_template
    attrs = merge_attrs({ data: { slot: "native-select", size: @size } }, @attrs.except(:class))
    previous = context[CONTEXT_KEY]
    context[CONTEXT_KEY] = { values: @selected, multiple: @multiple, taken: false }
    div(class: WRAPPER, data: { slot: "native-select-wrapper" }) do
      select(**attrs, class: cn(BASE, FOCUS, INVALID, @attrs[:class])) { yield self }
      render Chadcn::Icon.new("chevron-down", class: ICON, aria: { hidden: "true" }, data: { slot: "native-select-icon" })
    end
  ensure
    context[CONTEXT_KEY] = previous
  end
end
