# A form field: lays out a label, a control, a description and an error (shadcn `Field`).
#
# Renders `<div role="group">`; the block receives the field, so every part is available as a helper
# (`field.label`, `field.content`, `field.description`, `field.error`, `field.title`, `field.group`, `field.set`,
# `field.legend`, `field.separator`).
#
# @example
#   render Phlex::Shadcn::Field.new do |field|
#     field.label(html_for: "email") { "Email" }
#     field.render Phlex::Shadcn::Input.new(id: "email", type: "email")
#     field.description { "We never share it." }
#   end
#
# @!method set(**attrs, &block)
#   Renders {Field::Set}; same as +render Field::Set.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method legend(**attrs, &block)
#   Renders {Field::Legend}; same as +render Field::Legend.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method group(**attrs, &block)
#   Renders {Field::Group}; same as +render Field::Group.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method content(**attrs, &block)
#   Renders {Field::Content}; same as +render Field::Content.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method label(**attrs, &block)
#   Renders {Field::Label}; same as +render Field::Label.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method title(**attrs, &block)
#   Renders {Field::Title}; same as +render Field::Title.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method description(**attrs, &block)
#   Renders {Field::Description}; same as +render Field::Description.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method separator(**attrs, &block)
#   Renders {Field::Separator}; same as +render Field::Separator.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method error(**attrs, &block)
#   Renders {Field::Error}; same as +render Field::Error.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
class Phlex::Shadcn::Field < Phlex::Shadcn::Base
  # Root classes shared by every orientation.
  #
  # @return [String]
  # @api private
  BASE = "group/field flex w-full gap-3 data-[invalid=true]:text-destructive"
  # Orientation => Tailwind classes; the keys are the accepted values of `orientation:`.
  #
  # @return [Hash{String => String}]
  ORIENTATIONS = {
    "vertical" => "flex-col [&>*]:w-full [&>.sr-only]:w-auto",
    "horizontal" => "flex-row items-center [&>[data-slot=field-label]]:flex-auto has-[>[data-slot=field-content]]:items-start has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
    "responsive" => "flex-col @md/field-group:flex-row @md/field-group:items-center [&>*]:w-full @md/field-group:[&>*]:w-auto [&>.sr-only]:w-auto @md/field-group:[&>[data-slot=field-label]]:flex-auto @md/field-group:has-[>[data-slot=field-content]]:items-start @md/field-group:has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px"
  }.freeze

  # Class string of a field root, mirroring the (unexported) `fieldVariants` cva of the tsx.
  #
  # @param orientation [String, Symbol, nil] "vertical", "horizontal" or "responsive" (nil means "vertical"); other
  #   values are not validated and yield no orientation classes
  # @param class [String, nil] extra classes, merged last
  # @return [String]
  def self.variants(orientation: "vertical", class: nil)
    new(orientation:).send(:cn, BASE, ORIENTATIONS[(orientation || "vertical").to_s], binding.local_variable_get(:class))
  end

  # @param orientation [String, Symbol, nil] "vertical", "horizontal" or "responsive" (nil means "vertical"); other
  #   values are not validated: an unknown orientation renders no orientation classes
  # @param attrs [Hash] HTML attributes merged onto the root `<div>` (`class:`, `data:`, `aria:`...)
  def initialize(orientation: "vertical", **attrs)
    @orientation = (orientation || "vertical").to_s
    @attrs = attrs
    super()
  end

  # @yield [field] the field itself, to use the part helpers
  # @yieldparam field [Phlex::Shadcn::Field]
  # @return [void]
  def view_template(&block)
    attrs = merge_attrs(
      { role: "group", data: { slot: "field", orientation: @orientation }, class: [ BASE, ORIENTATIONS[@orientation] ] },
      @attrs
    )
    div(**attrs) { yield self if block }
  end

  # Groups related fields in a `<fieldset>` (helper: `field.set`).
