  # A rule between fields with optional centered text (helper: `field.separator`).
  #
  # @example
  #   field.separator { "Or continue with" }
  class Separator < Phlex::Shadcn::Base
    # Default separator classes.
    #
    # @return [String]
    # @api private
    CLASS_NAME = "relative -my-2 h-5 text-sm group-data-[variant=outline]/field-group:-mb-2"
    # Classes of the centered text span.
    #
    # @return [String]
    # @api private
    CONTENT_CLASS_NAME = "relative mx-auto block w-fit bg-background px-2 text-muted-foreground"

    # @param attrs [Hash] HTML attributes merged onto the `<div>`
    def initialize(**attrs)
      @attrs = attrs
      super()
    end

    # @yield optional text shown over the rule; `data-content` reflects whether it is present
    # @return [void]
    def view_template(&block)
      content = block ? capture(&block) : ""
      has_content = content.filled?
      attrs = merge_attrs({ data: { slot: "field-separator", content: has_content.to_s }, class: CLASS_NAME }, @attrs)
      div(**attrs) do
        render Phlex::Shadcn::Separator.new(class: "absolute inset-0 top-1/2")
        span(class: CONTENT_CLASS_NAME, data: { slot: "field-separator-content" }) { raw safe(content) } if has_content
      end
    end
  end

  # Validation messages, a `role="alert"` `<div>` (helper: `field.error`). Renders nothing when there is no content.
  #
  # Block content wins over `errors:`; one message renders as text, several as a bulleted list (duplicates removed).
  # Blank entries count toward the choice, so +[message, nil]+ renders a one-item list.
  #
  # @example
  #   field.error(errors: [ { message: "can't be blank" } ])
  class Error < Phlex::Shadcn::Base
    # Default classes.
    #
    # @return [String]
    # @api private
    CLASS_NAME = "text-sm font-normal text-destructive"

    # @param errors [Array<Hash, #message>, nil] error entries with a `:message` / `"message"` key or a `#message` method
    # @param attrs [Hash] HTML attributes merged onto the `<div>`
    def initialize(errors: nil, **attrs)
      @errors = errors
      @attrs = attrs
      super()
    end

    # Blank messages are dropped from a list, and a lone blank message renders nothing.
    #
    # @yield optional custom content that replaces `errors:`
    # @return [void]
    def view_template(&block)
      children = block ? capture(&block) : ""
      messages = children.filled? ? [] : unique_messages
      return if children.blank_value? && messages.reject_blank.empty?

      div(**merge_attrs({ role: "alert", data: { slot: "field-error" }, class: CLASS_NAME }, @attrs)) do
        if children.filled?
          raw safe(children)
        elsif messages.size == 1
          plain messages.first
        else
          ul(class: "ml-4 flex list-disc flex-col gap-1") { messages.reject_blank.each { |message| li { message } } }
        end
      end
    end

    private

    # Port of `new Map(errors.map(e => [e?.message, e])).values()`: dedupe by message, first occurrence order;
    # entries without a message share one key and render nothing.
    def unique_messages
      Array(@errors).map { |error| message_of(error) }.uniq
    end

    def message_of(error)
      return error[:message] || error["message"] if error.is_a?(Hash)

      error.message if error.respond_to?(:message)
    end
  end
