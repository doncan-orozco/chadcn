    # @param attrs [Hash] HTML attributes merged onto the `<fieldset>`
    def initialize(**attrs)
      @attrs = attrs
      super()
    end

    # @yield the fieldset content
    # @return [void]
    def view_template(&)
      fieldset(**merge_attrs({ data: { slot: "field-set" }, class: CLASS_NAME }, @attrs), &)
    end
  end

