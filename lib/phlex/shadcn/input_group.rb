# frozen_string_literal: true

# shadcn `InputGroup` (new-york-v4). Spec: docs/shadcn-port/specs/input-group.md
using Phlex::Shadcn::Values::Refinements

# Wraps an input with leading or trailing addons, buttons and text (shadcn `InputGroup`).
#
# Renders `<div role="group">`; the block receives the group, so every part is available as a helper
# (`group.addon`, `group.button`, `group.text`, `group.input`, `group.textarea`).
#
# @example
#   render Phlex::Shadcn::InputGroup.new do |group|
#     group.input(placeholder: "Search...")
#     group.addon(align: "inline-end") { group.button(size: "xs") { "Go" } }
#   end
#
# @!method addon(**attrs, &block)
#   Renders {InputGroup::Addon}; same as +render InputGroup::Addon.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method button(**attrs, &block)
#   Renders {InputGroup::Button}; same as +render InputGroup::Button.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method text(**attrs, &block)
#   Renders {InputGroup::Text}; same as +render InputGroup::Text.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method input(**attrs, &block)
#   Renders {InputGroup::Input}; same as +render InputGroup::Input.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
#
# @!method textarea(**attrs, &block)
#   Renders {InputGroup::Textarea}; same as +render InputGroup::Textarea.new(**attrs), &block+. Generated by +Base.const_added+.
#   @return [void]
class Phlex::Shadcn::InputGroup < Phlex::Shadcn::Base
  # Root classes, one string per concern (joined through `cn`).
  #
  # @api private
  CLASS_NAME = [
    "group/input-group relative flex w-full items-center rounded-md border border-input shadow-xs transition-[color,box-shadow] outline-none dark:bg-input/30",
    "h-9 min-w-0 has-[>textarea]:h-auto",
    "has-[>[data-align=inline-start]]:[&>input]:pl-2",
    "has-[>[data-align=inline-end]]:[&>input]:pr-2",
    "has-[>[data-align=block-start]]:h-auto has-[>[data-align=block-start]]:flex-col has-[>[data-align=block-start]]:[&>input]:pb-3",
    "has-[>[data-align=block-end]]:h-auto has-[>[data-align=block-end]]:flex-col has-[>[data-align=block-end]]:[&>input]:pt-3",
    "has-[[data-slot=input-group-control]:focus-visible]:border-ring has-[[data-slot=input-group-control]:focus-visible]:ring-[3px] has-[[data-slot=input-group-control]:focus-visible]:ring-ring/50",
    "has-[[data-slot][aria-invalid=true]]:border-destructive has-[[data-slot][aria-invalid=true]]:ring-destructive/20 dark:has-[[data-slot][aria-invalid=true]]:ring-destructive/40"
  ].freeze

  # @param attrs [Hash] HTML attributes merged onto the root `<div>`
  def initialize(**attrs)
    @attrs = attrs
  end

  # @yield [group] the group itself, to use the part helpers
  # @yieldparam group [Phlex::Shadcn::InputGroup]
  # @return [void]
  def view_template(&block)
    div(**merge_attrs({ role: "group", data: { slot: "input-group" }, class: cn(*CLASS_NAME) }, @attrs)) { yield self if block }
  end

  # Content placed beside or above/below the control (helper: `group.addon`). Clicking it focuses the control through the
  # `shadcn--input-group` controller, unless the caller passes its own `click` action.
  #
  # @example
  #   group.addon(align: "inline-start") { "https://" }
  class Addon < Phlex::Shadcn::Base
    # Classes shared by every alignment.
    #
    # @api private
    BASE = "flex h-auto cursor-text items-center justify-center gap-2 py-1.5 text-sm font-medium text-muted-foreground select-none group-data-[disabled=true]/input-group:opacity-50 [&>kbd]:rounded-[calc(var(--radius)-5px)] [&>svg:not([class*='size-'])]:size-4"

    # Alignment => Tailwind classes; the keys are the accepted values of `align:`.
    #
    # @return [Hash{String => String}]
    ALIGNS = {
      "inline-start" => "order-first pl-3 has-[>button]:ml-[-0.45rem] has-[>kbd]:ml-[-0.35rem]",
      "inline-end" => "order-last pr-3 has-[>button]:mr-[-0.45rem] has-[>kbd]:mr-[-0.35rem]",
      "block-start" => "order-first w-full justify-start px-3 pt-3 group-has-[>input]/input-group:pt-2.5 [.border-b]:pb-3",
      "block-end" => "order-last w-full justify-start px-3 pb-3 group-has-[>input]/input-group:pb-2.5 [.border-t]:pt-3"
    }.freeze

    # Stimulus identifier.
    #
    # @return [String]
    # @api private
    CONTROLLER = "shadcn--input-group"
    # Stimulus action descriptor.
    #
    # @return [String]
    # @api private
    ACTION = "click->shadcn--input-group#focusControl"

    # @param align [String, Symbol, nil] one of ALIGNS; nil means "inline-start"; underscores are normalized (`:inline_end`)
    # @param attrs [Hash] HTML attributes merged onto the addon `<div>`
    # @raise [ArgumentError] when the alignment is unknown
    def initialize(align: "inline-start", **attrs)
      @align = normalize_option(align) || "inline-start"
      raise ArgumentError, "unknown align: #{align.inspect} (expected one of #{ALIGNS.keys.join(', ')})" unless ALIGNS.key?(@align)

      @attrs = attrs
    end

    # @yield the addon content
    # @return [void]
    def view_template(&)
      caller_attrs = canonical_attrs(@attrs)
      defaults = { role: "group", data: { slot: "input-group-addon", align: @align }, class: cn(BASE, ALIGNS[@align]) }
      attrs = merge_attrs(defaults, caller_attrs.except(:class))
      attrs = attrs.merge(class: [ @slot_class, cn(BASE, ALIGNS[@align], caller_attrs[:class]) ].reject_blank.join(" "))
      attrs[:data] = wire_controller(attrs[:data] || {})
      div(**attrs, &)
    end

    private

    # A caller click action replaces the focus handler, like a React onClick spread after it (spec Behavior).
    def wire_controller(data)
      data = data.merge(controller: [ data[:controller], CONTROLLER ].reject_blank.flat_map(&:split).uniq.join(" "))
      return data if click_action?(data[:action])

      data.merge(action: [ data[:action], ACTION ].reject_blank.join(" "))
    end

    def click_action?(action)
      action.to_s.split.any? { |descriptor| descriptor.include?("->") ? descriptor.split("->").first.split(/[@.]/).first == "click" : true }
    end
  end

  # A small button for an addon; renders a `Phlex::Shadcn::Button` with its own size table (helper: `group.button`).
  #
  # @example
  #   group.button(variant: "secondary", size: "sm") { "Copy" }
  class Button < Phlex::Shadcn::Base
    # Classes added to the wrapped button.
    #
    # @api private
    BASE = "flex items-center gap-2 text-sm shadow-none"

    # Size name => Tailwind classes; the keys are the accepted values of `size:`.
    #
    # @return [Hash{String => String}]
    SIZES = {
      "xs" => "h-6 gap-1 rounded-[calc(var(--radius)-5px)] px-2 has-[>svg]:px-2 [&>svg:not([class*='size-'])]:size-3.5",
      "sm" => "h-8 gap-1.5 rounded-md px-2.5 has-[>svg]:px-2.5",
      "icon-xs" => "size-6 rounded-[calc(var(--radius)-5px)] p-0 has-[>svg]:p-0",
      "icon-sm" => "size-8 p-0 has-[>svg]:p-0"
    }.freeze

    # @param type [String] the button `type` attribute (defaults to "button")
    # @param variant [String, Symbol] a `Phlex::Shadcn::Button` variant (defaults to "ghost"); an unknown variant raises
    #   `ArgumentError` at render time, from `Phlex::Shadcn::Button`
    # @param size [String, Symbol, nil] one of SIZES (nil means "xs")
    # @param as_child [false, Symbol, String, Phlex::Shadcn::Base] see `Phlex::Shadcn::Button`; false renders the default `<button>`
    # @param attrs [Hash] HTML attributes forwarded to the button
    # @raise [ArgumentError] when the size is unknown (at construction)
    def initialize(type: "button", variant: "ghost", size: "xs", as_child: false, **attrs)
      @size = normalize_option(size) || "xs"
      raise ArgumentError, "unknown size: #{size.inspect} (expected one of #{SIZES.keys.join(', ')})" unless SIZES.key?(@size)

      @type = type
      @variant = variant
      @as_child = as_child
      @attrs = attrs
    end

    # @yield the button content
    # @return [void]
    def view_template(&)
      attrs = { type: @type, variant: @variant, as_child: @as_child, "data-size": @size }.merge(@attrs)
      attrs[:class] = cn(BASE, SIZES[@size], @attrs[:class])
      render(Phlex::Shadcn::Button.new(**attrs), &)
    end
  end

  # Muted inline text (a unit, a prefix) inside an addon (helper: `group.text`).
  #
  # @example
  #   group.text { "USD" }
  class Text < Phlex::Shadcn::Base
    # Default text classes.
    #
    # @api private
    CLASS_NAME = "flex items-center gap-2 text-sm text-muted-foreground [&_svg]:pointer-events-none [&_svg:not([class*='size-'])]:size-4"

    # @param attrs [Hash] HTML attributes merged onto the `<span>`
    def initialize(**attrs)
      @attrs = attrs
    end

    # @yield the text content
    # @return [void]
    def view_template(&)
      span(**merge_attrs({ class: CLASS_NAME }, @attrs), &)
    end
  end

  # The borderless `Phlex::Shadcn::Input` of the group, marked `data-slot="input-group-control"` (helper: `group.input`).
  #
  # @example
  #   group.input(type: "email", placeholder: "you@example.com")
  class Input < Phlex::Shadcn::Base
    # Default input classes.
    #
    # @api private
    CLASS_NAME = "flex-1 rounded-none border-0 bg-transparent shadow-none focus-visible:ring-0 dark:bg-transparent"

    # @param attrs [Hash] attributes forwarded to `Phlex::Shadcn::Input` (`type:`, `name:`, `placeholder:`...)
    def initialize(**attrs)
      @attrs = attrs
    end

    # @return [void]
    def view_template
      render Phlex::Shadcn::Input.new("data-slot": "input-group-control", **@attrs, class: cn(CLASS_NAME, @attrs[:class]))
    end
  end

  # The borderless `Phlex::Shadcn::Textarea` of the group, marked `data-slot="input-group-control"` (helper: `group.textarea`).
  #
  # @example
  #   group.textarea(rows: 3, placeholder: "Message")
  class Textarea < Phlex::Shadcn::Base
    # Default textarea classes.
    #
    # @api private
    CLASS_NAME = "flex-1 resize-none rounded-none border-0 bg-transparent py-3 shadow-none focus-visible:ring-0 dark:bg-transparent"

    # @param attrs [Hash] attributes forwarded to `Phlex::Shadcn::Textarea`
    def initialize(**attrs)
      @attrs = attrs
    end

    # @yield optional textarea content
    # @return [void]
    def view_template(&)
      render Phlex::Shadcn::Textarea.new("data-slot": "input-group-control", **@attrs, class: cn(CLASS_NAME, @attrs[:class])), &
    end
  end
end
