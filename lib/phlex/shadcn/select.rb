# frozen_string_literal: true

# shadcn Select (Radix Select). Behavior lives in controllers/shadcn/select_controller.js
# (hosted by the Trigger).
#
# The root renders no element: it pushes its state into the Phlex render context for the parts inside. Radix keeps the closed
# Content in a detached fragment so the items register and the content of the selected item (its HTML children) reaches
# Value before anything opens; the server has no fragment, so the block is rendered twice: a first pass where only the Items register themselves (value, text,
# html) and a second pass that renders the DOM with that registry known. The block therefore runs twice.
#
# The state is controlled when +value:+ / +open:+ is given (not +nil+): user actions then only dispatch the events below and the
# server decides the state by re-rendering. Otherwise the controller owns it, starting from +default_value:+ / +default_open:+.
#
# The Stimulus controller +shadcn--select+ (on the Trigger) dispatches +shadcn--select:value-change+ (+detail.value+) and
# +shadcn--select:open-change+ (+detail.open+), both non-cancelable. While open it also dispatches the cancelable
# +shadcn--select:escape-key-down+ and +shadcn--select:pointer-down-outside+ (+detail.originalEvent+; preventing them keeps the
# select open), and +shadcn--select:close-auto-focus+ when the content unmounts on closing (preventing it skips
# refocusing the trigger), but not while the controller disconnects (element removed, Turbo navigation or cache snapshot).
#
# Each nested part also has a public helper on the root, generated by +Base.const_added+ (see the +@!method+ entries).
#
# @example Uncontrolled select that submits with a form
#   render Phlex::Shadcn::Select.new(name: "fruit", default_value: "apple") do |select|
#     select.trigger(class: "w-48") { select.value(placeholder: "Pick a fruit") }
#     select.content do
#       select.group do
#         select.label { "Fruits" }
#         select.item(value: "apple") { "Apple" }
#         select.item(value: "banana", disabled: true) { "Banana" }
#       end
#       select.separator
#       select.item(value: "other") { "Other" }
#     end
#   end
# @example Controlled by the server
#   render Phlex::Shadcn::Select.new(value: @fruit, open: false) do |select|
#     select.trigger { select.value }
#     select.content { select.item(value: "apple") { "Apple" } }
#   end
#
# @!method trigger(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Trigger.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method value(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Value.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method content(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Content.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method group(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Group.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method label(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Label.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method item(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Item.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method separator(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::Separator.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method scroll_up_button(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::ScrollUpButton.new(**attrs), &block+; the block is the part's content.
#   @return [void]
#
# @!method scroll_down_button(**attrs, &block)
#   Sugar for +render Phlex::Shadcn::Select::ScrollDownButton.new(**attrs), &block+; the block is the part's content.
#   @return [void]
class Phlex::Shadcn::Select < Phlex::Shadcn::Base
  include Phlex::Shadcn::Direction::Consumer

  # @api private
  # @return [Symbol] render-context key under which the root publishes its state
  ROOT_KEY = :shadcn_select_root
  # @api private
  # @return [Symbol] render-context key holding the id of the enclosing Group (read by Label)
  GROUP_KEY = :shadcn_select_group
  # @api private
  # @return [Symbol] render-context key of the per-render counter behind generated ids
  SEQUENCE_KEY = :shadcn_select_sequence
  # @api private
  # @return [Array<String>] accepted +dir:+ values; anything else is ignored and the direction comes from the
  #   {Phlex::Shadcn::Direction} provider (default +ltr+)
  DIRECTIONS = %w[ltr rtl].freeze

  # value:/open: given (not nil) are controlled: user actions only dispatch events, the server decides the state.
  #
  # @param value [String, Symbol, Integer, nil] controlled selected value (converted with +to_s+); +nil+ means uncontrolled
  # @param default_value [String, Symbol, Integer, nil] initial value when uncontrolled; +nil+ shows the Value placeholder
  # @param open [Boolean, nil] controlled open state; +nil+ means uncontrolled
  # @param default_open [Boolean] initial open state when uncontrolled
  # @param dir [String, Symbol, nil] +"ltr"+ or +"rtl"+; other values are ignored and the direction provider (or +ltr+) is used
  # @param name [String, nil] when given, the Trigger also renders a visually hidden native +select+ with that name; the
  #   controller keeps it only inside a form or when +form:+ is set (+name:+ alone outside a form submits nothing)
  # @param auto_complete [String, nil] forwarded as +autocomplete+ to the hidden native select
  # @param form [String, nil] id of the form the hidden native select belongs to (also renders it, and keeps it outside a form)
  # @param disabled [Boolean] disables the Trigger and the hidden native select
  # @param required [Boolean, nil] +aria-required+ on the Trigger (+nil+ omits it, +false+ renders +"false"+) and +required+ on the hidden
  #   native select (only +true+)
  # @param id [String, nil] base for the generated ids (+"#{id}-content"+...); a per-render +select-N+ is used when +nil+
  # @return [void]
  def initialize(value: nil, default_value: nil, open: nil, default_open: false, dir: nil, name: nil, auto_complete: nil,
                 form: nil, disabled: false, required: nil, id: nil)
    @options = {
      controlled_value: !value.nil?, value: (value.nil? ? default_value : value)&.to_s,
      controlled_open: !open.nil?, open: open.nil? ? default_open : open,
      dir: (dir.to_s if DIRECTIONS.include?(dir.to_s)),
      name:, auto_complete:, form:, disabled:, required:, base: id
    }
    super()
  end

  # Renders the block twice (collect, then render) and nothing of its own.
  #
  # @yieldparam select [Phlex::Shadcn::Select] the root itself, which carries the part helpers
  # @return [void]
  def view_template(&block)
    previous = context[ROOT_KEY]
    state = context[ROOT_KEY] =
      @options.merge(dir: use_direction(@options[:dir]), base: @options[:base] || "select-#{next_sequence}", known: [], phase: :collect)
    if block
      capture { yield self }
      state[:phase] = :render
      state[:counter] = 0
      yield self
    end
  ensure
    context[ROOT_KEY] = previous
  end

  private

  # Per render counter (no SecureRandom): ids are only compared through their relations.
  def next_sequence = context[SEQUENCE_KEY] = context.fetch(SEQUENCE_KEY, 0) + 1
end
